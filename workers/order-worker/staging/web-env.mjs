/** = tools/firebase-env-guard.ts STAGING_ENV_DIR (vite.config.ts envDir in mode "staging") */
export const STAGING_ENV_DIR = 'env/staging';

// Writes <repo>/env/staging/.env.staging.local (git-ignored) for `npm run dev:staging` from staging.config.json's STAGING web
// config. Public identifiers only (web API key, app id) — never a secret. Refuses to overwrite an existing file.
//   node staging/web-env.mjs --config staging/staging.config.json [--proxy-port 8789]

import { writeFileSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { pathToFileURL } from 'node:url';
import { assertStagingConfig, loadStagingConfigFile, StagingGuardError, REPO_ROOT, STAGING_PROJECT_ID } from './guard.mjs';
import { DEFAULT_PROXY_PORT } from './proxy.mjs';
import { parseArgs, runCli } from './common.mjs';

export function stagingWebEnv(st, proxyPort = DEFAULT_PROXY_PORT) {
  if (st.projectId !== STAGING_PROJECT_ID) throw new StagingGuardError([`web env is for ${STAGING_PROJECT_ID} only`]);
  const w = st.firebaseWebConfig;
  return [
    '# generated by workers/order-worker/staging/web-env.mjs — staging web config (public identifiers only, no secrets)',
    'VITE_FIREBASE_TARGET=staging',
    `VITE_FIREBASE_PROJECT_ID=${st.projectId}`,
    `VITE_FIREBASE_API_KEY=${w.apiKey}`,
    `VITE_FIREBASE_APP_ID=${w.appId}`,
    `VITE_FIREBASE_AUTH_DOMAIN=${w.authDomain}`,
    `VITE_WORKER_URL=http://127.0.0.1:${proxyPort}`,
    // Cloudflare's PUBLIC always-pass TEST site key (matches the staging Worker's TEST secret) — not a secret
    'VITE_TURNSTILE_SITE_KEY=1x00000000000000000000AA',
    '',
  ].join('\n');
}

export async function main(argv, deps = {}) {
  const a = parseArgs(argv);
  const st = assertStagingConfig(deps.config ?? loadStagingConfigFile(a.config), { env: deps.env ?? process.env });
  const port = a['proxy-port'] === undefined ? DEFAULT_PROXY_PORT : Number(a['proxy-port']);
  if (!Number.isInteger(port) || port < 1024 || port > 65535) throw new StagingGuardError(['--proxy-port must be 1024..65535']);
  // env/staging/ = vite.config.ts envDir for `vite --mode staging` (the repository root's .env files are never used)
  const out = deps.out ?? resolve(REPO_ROOT, STAGING_ENV_DIR, '.env.staging.local');
  mkdirSync(dirname(out), { recursive: true });
  try {
    writeFileSync(out, stagingWebEnv(st, port), { flag: 'wx' });
  } catch (e) {
    if (e?.code === 'EEXIST') throw new StagingGuardError([`${out} already exists — not replaced`]);
    throw e;
  }
  console.log(`wrote ${out} (staging target, proxy http://127.0.0.1:${port}; no secrets)`);
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) runCli(main);
